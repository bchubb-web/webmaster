<?php

namespace Webmaster\Core;

use Nette\PhpGenerator\Printer;
use Webmaster\CoreInterface;

/**
 * This class is used to create a serialised version of the core
 * with classname \Webmaster\Core\Compiled
 */
class Compiler
{
    public function __construct(
        protected Printer $printer
    ) {
        $this->printer->indentation = '    ';
        $this->printer->linesBetweenMethods = 1;
    }

    public function __invoke(CoreInterface $core): string
    {

        // if $core is an instance of \Webmaster\Core\Compiled, find the original class that it extends and use that instead
        if ($core instanceof \Webmaster\Core\Compiled) {
            $parentClass = get_parent_class($core);
            if ($parentClass !== false) {
                $core = new $parentClass();
            }
        }


        $file = new \Nette\PhpGenerator\PhpFile();
        $file->setStrictTypes();
        $file->addComment('This file is generated by \Webmaster\Core\Compiler and should not be modified manually.');

        $namespace = new \Nette\PhpGenerator\PhpNamespace("Webmaster\\Core");
        $target = new \Nette\PhpGenerator\ClassType('Compiled');
        $namespace->add($target);
        $file->addNamespace($namespace);

        $target
            ->setFinal()
            ->setExtends($core::class)
            ->setComment('This class is generated by the SerialisedCompiler and should not be modified manually.')
        ;

        $getEntitiesMethod = $target->addMethod('getEntities')
            ->setPublic()
            ->setReturnType('array')
            ->setBody('return [...?];', [$core->getEntities()]);

        ;

        return $this->printer->printFile($file);
    }
}
